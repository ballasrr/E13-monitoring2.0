"""Определение адреса клиента за обратным прокси.

Отсюда берётся ключ ограничителя попыток входа. Ошибка здесь не ломает
ничего видимого — она просто делает защиту от подбора пароля
бесполезной, и заметить это можно только по факту взлома.
"""
from app.routers.deps import client_ip


class FakeClient:
    def __init__(self, host: str) -> None:
        self.host = host


class FakeRequest:
    """Минимальная заглушка: нужны только заголовки и адрес сокета."""

    def __init__(self, forwarded: str | None = None, peer: str | None = "10.0.0.1"):
        self.headers = {"x-forwarded-for": forwarded} if forwarded else {}
        self.client = FakeClient(peer) if peer else None


def test_без_прокси_берётся_адрес_сокета():
    assert client_ip(FakeRequest(peer="203.0.113.7")) == "203.0.113.7"


def test_за_прокси_берётся_адрес_дописанный_прокси():
    """Caddy дописывает настоящий адрес в конец цепочки."""
    assert client_ip(FakeRequest("203.0.113.7")) == "203.0.113.7"


def test_подделанный_заголовок_не_обманывает():
    """Клиент прислал свой X-Forwarded-For, прокси дописал настоящий
    адрес справа. Берём правый — подделка игнорируется.

    Если бы брали левый, подбирающий пароль менял бы выдуманный адрес
    на каждом запросе и получал неограниченное число попыток.
    """
    forged = "1.1.1.1, 2.2.2.2, 203.0.113.7"
    assert client_ip(FakeRequest(forged)) == "203.0.113.7"


def test_пробелы_и_пустые_элементы_не_мешают():
    assert client_ip(FakeRequest("  1.1.1.1 ,, 203.0.113.7  ")) == "203.0.113.7"


def test_без_адреса_вообще_возвращается_заглушка():
    """Так бывает при вызовах изнутри, без сетевого подключения.
    Главное — не упасть: вход важнее учёта попыток."""
    assert client_ip(FakeRequest(peer=None)) == "unknown"
